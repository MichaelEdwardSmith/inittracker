		<div class="space-y-6 text-base leading-relaxed text-gray-300">
			<p>Hello, adventurer.</p>

			<p>
				You've just rolled into my little corner of the internet, so first things first: you
				succeeded on your Perception check. The snacks are on the left, the exits are everywhere,
				and there are no mimics. (Probably.)
			</p>

			<p>
				I built this tool because I love Dungeons &amp; Dragons, and I want as many people as
				possible to get to play it.
			</p>

			<p>
				Everyone has heard the story. Someone says "we should play D&amp;D sometime," and then
				nobody has a rulebook, the DM is drowning in index cards, initiative order turns into a bar
				fight, and the campaign dies in session zero. I've been in that group. I'd like to help
				prevent it.
			</p>

			<p>So this is what I'm trying to do:</p>

			<ul class="list-inside list-disc space-y-3">
				<li>
					<span class="font-semibold text-gray-100">Make running combat easier,</span> so DMs spend less
					time on bookkeeping and more time doing voices that are slightly too good.
				</li>
				<li>
					<span class="font-semibold text-gray-100">Make the table welcoming,</span> so a first-timer
					can join a session without feeling like they skipped the tutorial.
				</li>
				<li>
					<span class="font-semibold text-gray-100">Keep it free to try and simple to start,</span>
					because the hobby shouldn't have a gate. Nat 1s are the only gatekeepers we need.
				</li>
			</ul>

			<p>
				I'm not claiming this is the best tool ever made. It's one person's love letter to a game
				that has given me years of laughter, terrible puns, and one tragic incident involving a
				gelatinous cube. I'm still adding things and fixing things. I still occasionally trip over
				my own code like a rogue who forgot to disarm the trap.
			</p>

			<p>
				If something's broken, confusing, or missing, tell me. Every bit of feedback makes the tool
				better for the next table. If it helps your game run a little smoother, then I've done my
				job.
			</p>

			<p>
				Thank you for stopping by. Whether you're a veteran DM with forty years of campaigns or
				someone who just bought their first set of dice and doesn't know which one is the pointy
				one, you're welcome here.
			</p>

			<p>Now go roll for initiative. I hope it's a 20.</p>

